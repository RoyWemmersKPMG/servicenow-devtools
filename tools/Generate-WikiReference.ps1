$ErrorActionPreference = 'Stop'

$projectRoot = Split-Path -Parent $PSScriptRoot
$updateRoot = Join-Path $projectRoot 'update'
$referenceRoot = Join-Path $projectRoot 'docs\reference'

New-Item -ItemType Directory -Force -Path $referenceRoot | Out-Null

function Get-Record {
    param(
        [Parameter(Mandatory)] [System.IO.FileInfo] $File,
        [Parameter(Mandatory)] [string] $RecordName
    )

    $document = [System.Xml.XmlDocument]::new()
    $document.PreserveWhitespace = $false
    $document.Load($File.FullName)
    return $document.SelectSingleNode("/record_update/$RecordName")
}

function Get-Field {
    param(
        [Parameter(Mandatory)] [System.Xml.XmlNode] $Record,
        [Parameter(Mandatory)] [string] $Name
    )

    $node = $Record.SelectSingleNode($Name)
    if ($null -eq $node) {
        return ''
    }
    return $node.InnerText.Trim()
}

function ConvertTo-MarkdownCell {
    param([AllowEmptyString()] [string] $Value)

    if ($null -eq $Value) {
        return ''
    }
    return (($Value -replace '\|', '\|') -replace "\r?\n", '<br>')
}

function ConvertTo-MarkdownTable {
    param(
        [Parameter(Mandatory)] [object[]] $Rows,
        [Parameter(Mandatory)] [string[]] $Columns
    )

    $lines = [System.Collections.Generic.List[string]]::new()
    $lines.Add('| ' + ($Columns -join ' | ') + ' |')
    $lines.Add('| ' + (($Columns | ForEach-Object { '---' }) -join ' | ') + ' |')
    foreach ($row in $Rows) {
        $cells = foreach ($column in $Columns) {
            ConvertTo-MarkdownCell ([string]$row.$column)
        }
        $lines.Add('| ' + ($cells -join ' | ') + ' |')
    }
    return $lines -join [Environment]::NewLine
}

function Write-Markdown {
    param(
        [Parameter(Mandatory)] [string] $Path,
        [Parameter(Mandatory)] [string] $Content
    )

    $utf8NoBom = [System.Text.UTF8Encoding]::new($false)
    [System.IO.File]::WriteAllText($Path, $Content.TrimEnd() + [Environment]::NewLine, $utf8NoBom)
}

function Read-Records {
    param(
        [Parameter(Mandatory)] [string] $Pattern,
        [Parameter(Mandatory)] [string] $RecordName
    )

    foreach ($file in Get-ChildItem -LiteralPath $updateRoot -File -Filter $Pattern) {
        $record = Get-Record -File $file -RecordName $RecordName
        if ($null -ne $record) {
            $record
        }
    }
}

